// Embeds the end-user guides (../docs/user-guides/*.md, outside the app folder) into
// src/content/guides.generated.ts so the in-app Help Centre works on Vercel, which builds only app/.
// Usage: npm run guides   (idempotent: rewrites the file only when a guide changed)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.resolve(appDir, "..", "docs", "user-guides");
const outFile = path.join(appDir, "src", "content", "guides.generated.ts");

// File slug -> app role. Order here is the tab order in the Help Centre.
const ROLE_BY_SLUG = {
  "owner-admin": "admin",
  sales: "sales",
  purchase: "purchase",
  accounts: "accounts",
  "site-engineer": "engineer",
  store: "store",
};

if (!fs.existsSync(srcDir)) {
  console.log(`[guides] ${srcDir} not found; keeping the existing ${path.relative(appDir, outFile)}`);
  process.exit(0);
}

const files = fs.readdirSync(srcDir).filter((f) => f.endsWith(".md"));
const order = Object.keys(ROLE_BY_SLUG);
const guides = files
  .map((f) => {
    const slug = f.replace(/\.md$/, "");
    const markdown = fs.readFileSync(path.join(srcDir, f), "utf8").replace(/\r\n/g, "\n").trim() + "\n";
    const heading = (markdown.match(/^#\s+(.+)$/m)?.[1] ?? slug).trim();
    const title = heading.replace(/^User Guide:\s*/i, "").trim();
    return { slug, title, role: ROLE_BY_SLUG[slug] ?? null, markdown };
  })
  .sort((a, b) => {
    const ia = order.indexOf(a.slug), ib = order.indexOf(b.slug);
    return (ia < 0 ? 99 : ia) - (ib < 0 ? 99 : ib) || a.slug.localeCompare(b.slug);
  });

// Escape non-ASCII so the generated source stays plain ASCII (content is unchanged once parsed).
const json = JSON.stringify(guides, null, 2).replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));

const out = `// AUTO-GENERATED by scripts/embed-guides.mjs from docs/user-guides/*.md. Do not edit; run \`npm run guides\`.
import type { Role } from "@/lib/constants";

export type Guide = { slug: string; title: string; role: Role | null; markdown: string };

export const GUIDES: Guide[] = ${json};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
const prev = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
if (prev === out) console.log(`[guides] ${guides.length} guides, no changes`);
else {
  fs.writeFileSync(outFile, out);
  console.log(`[guides] embedded ${guides.length} guides into ${path.relative(appDir, outFile)}`);
}
